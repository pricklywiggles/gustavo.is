// Pacing math needs intrinsic layer sizes: yPercent travel is a fraction of the rendered box.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { sharp } from "./sharp.mjs";

const CITIES = ["seattle", "san-francisco", "los-angeles"];
const OUT = "src/components/landing/panorama-dimensions.ts";

const entries = [];
for (const city of CITIES) {
	const dir = join("public", `${city}-panorama`);
	for (const file of readdirSync(dir)
		.filter((f) => f.endsWith(".webp"))
		.sort()) {
		const { width, height } = await sharp(join(dir, file)).metadata();
		entries.push([`/${city}-panorama/${file}`, width, height]);
	}
}

const lines = entries.map(([src, w, h]) => `\t"${src}": { w: ${w}, h: ${h} },`);
writeFileSync(
	OUT,
	`// Generated by scripts/panorama-dimensions.mjs from public/*-panorama; do not edit.
export const PANORAMA_DIMENSIONS: Record<string, { w: number; h: number }> = {
${lines.join("\n")}
};
`,
);
console.log(`${OUT}: ${entries.length} layers`);
